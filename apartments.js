const languageButtons = document.querySelectorAll("[data-language]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const translatableLabels = document.querySelectorAll("[data-i18n-aria-label]");
const translatablePlaceholders = document.querySelectorAll("[data-i18n-placeholder]");
const zoneButtons = document.querySelectorAll("[data-zone]");
let currentLanguage = "ru";
let selectedZone = null;

function updateZoneDetails() {
    if (!selectedZone) {
        return;
    }

    const detailsByLanguage = zonesData[selectedZone];
    const details = detailsByLanguage?.[currentLanguage];
    if (!details) {
        throw new Error(`Zone details not found: ${selectedZone} (${currentLanguage})`);
    }

    const selectedIndex = Array.from(zoneButtons).findIndex((button) => button.dataset.zone === selectedZone);
    if (selectedIndex < 0) {
        throw new Error(`Zone button not found: ${selectedZone}`);
    }
    document.querySelector("#zone-index").textContent = String(selectedIndex + 1).padStart(2, "0");
    document.querySelector("#zone-title").textContent = details.title;
    document.querySelector("#zone-description").textContent = details.desc;
}

function setLanguage(language) {
    const languageStrings = translations[language];
    if (!languageStrings) {
        throw new RangeError(`Unsupported language: ${language}`);
    }

    currentLanguage = language;
    document.documentElement.lang = language;

    translatableElements.forEach((element) => {
        const translation = languageStrings[element.dataset.i18n];
        if (translation === undefined) {
            throw new Error(`Missing translation: ${language}.${element.dataset.i18n}`);
        }
        element.textContent = translation;
    });

    translatableLabels.forEach((element) => {
        const translation = languageStrings[element.dataset.i18nAriaLabel];
        if (translation === undefined) {
            throw new Error(`Missing accessible label translation: ${language}.${element.dataset.i18nAriaLabel}`);
        }
        element.setAttribute("aria-label", translation);
    });

    translatablePlaceholders.forEach((element) => {
        const translation = languageStrings[element.dataset.i18nPlaceholder];
        if (translation === undefined) {
            throw new Error(`Missing placeholder translation: ${language}.${element.dataset.i18nPlaceholder}`);
        }
        element.setAttribute("placeholder", translation);
    });

    const purchaseStatus = document.querySelector("#purchase-status");
    if (!purchaseStatus.hidden) {
        purchaseStatus.textContent = languageStrings.form_not_sent;
    }

    languageButtons.forEach((button) => {
        const isActive = button.dataset.language === language;
        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    updateZoneDetails();
}

languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.language);
    });
});

zoneButtons.forEach((button) => {
    button.addEventListener("click", () => {
        const zone = button.dataset.zone;
        if (!zonesData[zone]) {
            throw new Error(`Zone not found: ${zone}`);
        }

        selectedZone = zone;
        zoneButtons.forEach((zoneButton) => {
            const isSelected = zoneButton === button;
            zoneButton.classList.toggle("is-selected", isSelected);
            zoneButton.setAttribute("aria-pressed", String(isSelected));
        });
        updateZoneDetails();
    });
});

document.querySelectorAll("[data-dialog]").forEach((button) => {
    button.addEventListener("click", () => {
        const dialog = document.getElementById(button.dataset.dialog);
        if (!(dialog instanceof HTMLDialogElement)) {
            throw new Error(`Dialog not found: ${button.dataset.dialog}`);
        }
        dialog.showModal();
    });
});

document.querySelectorAll("[data-close-dialog]").forEach((link) => {
    link.addEventListener("click", () => {
        link.closest("dialog")?.close();
    });
});

document.querySelector("#purchase-form").addEventListener("submit", (event) => {
    event.preventDefault();
    const status = document.querySelector("#purchase-status");
    status.textContent = translations[currentLanguage].form_not_sent;
    status.hidden = false;
});

document.querySelectorAll("dialog").forEach((dialog) => {
    dialog.addEventListener("click", (event) => {
        if (event.target === dialog) {
            dialog.close();
        }
    });
});

const liquidLens = document.querySelector("#liquidLens");
let lensPressed = false;

document.addEventListener("pointerdown", (event) => {
    if (event.pointerType !== "mouse") {
        return;
    }

    lensPressed = true;
    liquidLens.style.left = `${event.clientX}px`;
    liquidLens.style.top = `${event.clientY}px`;
    liquidLens.classList.add("active");
});

document.addEventListener("pointermove", (event) => {
    if (lensPressed && event.pointerType === "mouse") {
        liquidLens.style.left = `${event.clientX}px`;
        liquidLens.style.top = `${event.clientY}px`;
    }
});

const releaseLens = () => {
    lensPressed = false;
    liquidLens.classList.remove("active");
};

document.addEventListener("pointerup", releaseLens);
document.addEventListener("pointercancel", releaseLens);
